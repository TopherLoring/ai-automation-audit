"""Generate Markdown and JSON reports from findings."""

from __future__ import annotations
import json
from datetime import datetime, timezone
from pathlib import Path
from .checks.base import Finding, Severity, SEVERITY_ORDER


def sort_findings(findings: list[Finding]) -> list[Finding]:
    return sorted(findings, key=lambda f: (SEVERITY_ORDER[f.severity], f.check_id))


def render_markdown(workflow_name: str, findings: list[Finding], meta: dict | None = None) -> str:
    findings = sort_findings(findings)
    meta = meta or {}
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    counts = {s.value: 0 for s in Severity}
    for f in findings:
        counts[f.severity.value] += 1

    lines = [
        f"# Automation Audit Report",
        f"",
        f"**Workflow:** {workflow_name}",
        f"**Generated:** {now}",
        f"**Engine version:** {meta.get('engine_version', '1.0.0')}",
        f"",
        f"## Summary",
        f"",
        f"| Severity   | Count |",
        f"|------------|-------|",
        f"| Critical   | {counts['critical']} |",
        f"| High       | {counts['high']} |",
        f"| Medium     | {counts['medium']} |",
        f"| Low        | {counts['low']} |",
        f"| Info       | {counts['info']} |",
        f"| **Total**  | **{len(findings)}** |",
        f"",
    ]

    if not findings:
        lines += [
            "## Result",
            "",
            "No issues detected by the current static ruleset. "
            "This does **not** guarantee the workflow is production-safe; "
            "runtime testing and monitoring are still required.",
            "",
        ]
        return "\n".join(lines)

    # Prioritized fix list
    lines += [
        "## Prioritized Repair List",
        "",
        "Fix in this order. Effort estimates are active minutes for an experienced n8n user.",
        "",
    ]

    for i, f in enumerate(findings, 1):
        node = f" (`{f.node_name}`)" if f.node_name else ""
        lines += [
            f"### {i}. [{f.severity.value.upper()}] {f.title}{node}",
            f"",
            f"**Check ID:** `{f.check_id}`  ",
            f"**Effort:** ~{f.effort_minutes} min  ",
            f"**Tags:** {', '.join(f.tags) or '—'}",
            f"",
            f"{f.description}",
            f"",
            f"**Evidence**",
            f"",
            f"```",
            f"{f.evidence}",
            f"```",
            f"",
            f"**Recommended fix**",
            f"",
            f"{f.recommendation}",
            f"",
            f"---",
            f"",
        ]

    lines += [
        "## Next Steps",
        "",
        "1. Apply the Critical and High fixes first.",
        "2. Re-export the workflow JSON and re-run this audit to confirm the findings are cleared.",
        "3. Perform a controlled runtime test (happy path + forced failure) before returning the workflow to production.",
        "4. Optionally request a separate implementation quote for any remaining structural work.",
        "",
        "---",
        "*Report generated by AI Automation Audit & Rescue engine. Static analysis only — not a substitute for runtime testing or security review.*",
        "",
    ]
    return "\n".join(lines)


def render_json(workflow_name: str, findings: list[Finding], meta: dict | None = None) -> str:
    payload = {
        "workflow_name": workflow_name,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "engine_version": (meta or {}).get("engine_version", "1.0.0"),
        "summary": {
            s.value: sum(1 for f in findings if f.severity == s) for s in Severity
        },
        "findings": [f.to_dict() for f in sort_findings(findings)],
    }
    return json.dumps(payload, indent=2)


def write_reports(
    workflow_name: str,
    findings: list[Finding],
    out_dir: str | Path,
    meta: dict | None = None,
) -> tuple[Path, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    safe_name = "".join(c if c.isalnum() or c in "-_" else "_" for c in workflow_name)[:60]
    md_path = out / f"{safe_name}_audit.md"
    json_path = out / f"{safe_name}_audit.json"

    md_path.write_text(render_markdown(workflow_name, findings, meta), encoding="utf-8")
    json_path.write_text(render_json(workflow_name, findings, meta), encoding="utf-8")
    return md_path, json_path